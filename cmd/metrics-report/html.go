const (
	svgWidth   = 900
	svgHeight  = 260
	svgPadL    = 60
	svgPadR    = 20
	svgPadT    = 20
	svgPadB    = 40
	svgLegendH = 22
)

// svgPalette mirrors the PNG palette so colors stay consistent.
var svgPalette = []string{
	"#2563eb", "#dc2626", "#16a34a", "#a855f7",
	"#ea580c", "#0ea5e9", "#a16207", "#db2777",
}

// renderHTMLReport writes a single-page self-contained HTML with inline SVG
// charts for every (suite, metric, job) combination. comparisonHTML, if
// non-empty, is embedded near the top as a pre-formatted HTML block.
func renderHTMLReport(jobs []jobData, outputDir, comparisonHTML string) (string, error) {
	suiteSet := make(map[string]struct{})
	for _, job := range jobs {
		for _, suite := range job.Suites {
			suiteSet[suite.Name] = struct{}{}
		}
	}
	suiteNames := make([]string, 0, len(suiteSet))
	for name := range suiteSet {
		suiteNames = append(suiteNames, name)
	}
	slices.Sort(suiteNames)

	jobSuiteMap := make(map[string]map[string][]metricsSample)
	for _, job := range jobs {
		jobSuiteMap[job.Name] = make(map[string][]metricsSample)
		for _, suite := range job.Suites {
			jobSuiteMap[job.Name][suite.Name] = suite.Samples
		}
	}

	var b strings.Builder
	writeHTMLHeader(&b)

	if comparisonHTML != "" {
		b.WriteString(comparisonHTML)
	}

	for _, suiteName := range suiteNames {
		writeHTMLSuite(&b, suiteName, jobs, jobSuiteMap)
	}

	writeHTMLFooter(&b)

	path := outputDir + "/metrics-report.html"
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return "", fmt.Errorf("writing HTML report: %w", err)
	}
	return path, nil
}

