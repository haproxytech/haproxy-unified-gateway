package main

import (
	"slices"
	"strconv"
	"strings"
	"text/template"
)

// leg is one generated job: a job set paired with one shard of the suite.
type leg struct {
	Name         string
	Stage        string
	SkipTests    string
	Shard        string
	AllowFailure bool
	Tests        int
}

// childPipeline is everything the template needs to render.
type childPipeline struct {
	Stages  []string
	Legs    []leg
	Reports []report
}

// report is the job following the shards: it merges their JUnit files and
// diffs the merged run against the previous scheduled one.
type report struct {
	Name  string
	Stage string
}

// reportJobName keeps the name the diff and its history use.
const (
	reportJobName = "conformance-report"
	reportStage   = "conformance-report"
)

const pipelineTemplate = `# Generated by cmd/gitlab-conformance-jobs. Do not edit.
include:
  - local: .gitlab/.conformance.yml

stages:
{{- range .Stages }}
  - {{ . }}
{{- end }}
{{ range .Legs }}
"{{ .Name }}":
  extends: .conformance-shard
  stage: {{ .Stage }}
  rules:
    - when: on_success
{{- if .AllowFailure }}
  allow_failure: true
{{- end }}
  variables:
    # Names this shard's result files, so the report job can collect them all.
    CONFORMANCE_SHARD: "{{ .Shard }}"
    # Owned by the other shards; the suite skips what it cannot run, and the
    # union of the shards still covers the whole suite.
    CONFORMANCE_SKIP_TESTS: "{{ .SkipTests }}"
{{ end }}{{ range .Reports }}
"{{ .Name }}":
  stage: {{ .Stage }}
  # Runs even when a shard failed: the shards upload their results regardless,
  # and a diff against the previous run is most useful then.
  rules:
    - when: always
  image:
    name: $HAPROXY_REGISTRY_GO/golang:latest-alpine
    entrypoint: [""]
  tags:
    - go
  variables:
    JUNIT_FILE: "reports/conformance-junit.xml"
  script:
    - mkdir -p reports
    - go run ./cmd/junit-merge -o "$JUNIT_FILE" conformance-junit-*.xml
    - go run ./cmd/conformance-diff
  artifacts:
    when: always
    paths:
      - reports/
{{ end }}`

const noJobsTemplate = `# Generated by cmd/gitlab-conformance-jobs. Do not edit.
include:
  - local: .gitlab/.conformance.yml

stages:
  - conformance-tests

conformance-no-jobs:
  stage: conformance-tests
  rules:
    - when: on_success
  script:
    - echo "no conformance job set matches this pipeline"
`

// buildPipeline turns each job set's shards into one job each, plus the report
// job when the set asks for one.
func buildPipeline(jobs []JobSet, names []string) childPipeline {
	pipeline := childPipeline{Stages: []string{}, Legs: []leg{}, Reports: []report{}}
	for _, job := range jobs {
		shards := shardTests(names, job.Shards)
		if len(shards) == 0 {
			continue
		}
		if !slices.Contains(pipeline.Stages, job.Stage) {
			pipeline.Stages = append(pipeline.Stages, job.Stage)
		}
		for shard, mine := range shards {
			pipeline.Legs = append(pipeline.Legs, leg{
				Name:         job.Name + ":" + strconv.Itoa(shard+1) + "/" + strconv.Itoa(len(shards)),
				Stage:        job.Stage,
				Tests:        len(mine),
				SkipTests:    skipList(names, mine),
				Shard:        strconv.Itoa(shard + 1),
				AllowFailure: job.AllowFailure,
			})
		}
		if job.Report {
			if !slices.Contains(pipeline.Stages, reportStage) {
				pipeline.Stages = append(pipeline.Stages, reportStage)
			}
			pipeline.Reports = append(pipeline.Reports, report{Name: reportJobName, Stage: reportStage})
		}
	}
	return pipeline
}

// shardTests deals the tests round robin, so the shards differ by at most one
// test. Empty shards are dropped, so asking for more shards than tests is
// harmless.
func shardTests(names []string, shards int) [][]string {
	if shards < 1 {
		return nil
	}
	dealt := make([][]string, shards)
	for i, name := range names {
		dealt[i%shards] = append(dealt[i%shards], name)
	}
	filled := make([][]string, 0, shards)
	for _, shard := range dealt {
		if len(shard) > 0 {
			filled = append(filled, shard)
		}
	}
	return filled
}

// skipList names every test the shard does not own, in upstream order. The
// suite has no "only these" switch, so a shard is told what to skip.
func skipList(names, mine []string) string {
	owned := make(map[string]bool, len(mine))
	for _, name := range mine {
		owned[name] = true
	}
	skipped := make([]string, 0, len(names)-len(mine))
	for _, name := range names {
		if !owned[name] {
			skipped = append(skipped, name)
		}
	}
	return strings.Join(skipped, ",")
}

// render turns the pipeline into child pipeline YAML.
func render(p childPipeline) (string, error) {
	body := pipelineTemplate
	if len(p.Legs) == 0 {
		body = noJobsTemplate
	}
	parsed, err := template.New("pipeline").Parse(body)
	if err != nil {
		return "", err
	}
	out := &strings.Builder{}
	if err = parsed.Execute(out, p); err != nil {
		return "", err
	}
	return out.String(), nil
}
